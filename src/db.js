/**
 * Converts `?` placeholders to Postgres `$1, $2…`, skipping string literals,
 * quoted identifiers, dollar-quoted bodies and comments.
 */
function toPositional(sql) {
  let out = '';
  let n = 0;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'" || c === '"') {
      const end = sql.indexOf(c, i + 1);
      const stop = end === -1 ? sql.length : end;
      out += sql.slice(i, stop + 1);
      i = stop;
    } else if (c === '-' && sql[i + 1] === '-') {
      const end = sql.indexOf('\n', i);
      const stop = end === -1 ? sql.length : end;
      out += sql.slice(i, stop);
      i = stop - 1;
    } else if (c === '$' && /[A-Za-z_$]/.test(sql[i + 1] || '')) {
      const tag = /^\$[A-Za-z_]*\$/.exec(sql.slice(i));
      if (tag) {
        const end = sql.indexOf(tag[0], i + tag[0].length);
        const stop = end === -1 ? sql.length : end + tag[0].length;
        out += sql.slice(i, stop);
        i = stop - 1;
      } else out += c;
    } else if (c === '?') {
      out += `$${++n}`;
    } else out += c;
  }
  return out;
}

const RETRYABLE = new Set(['40001', '40P01']); // serialization failure, deadlock

class Database {
  /**
   * @param {object} driver { query(text, params) -> {rows, rowCount}, exec(sql), transaction(fn), close() }
   */
  constructor(driver, { inTransaction = false } = {}) {
    this.driver = driver;
    this.inTransaction = inTransaction;
  }

  async query(sql, params = []) {
    return this.driver.query(toPositional(sql), params);
  }

  async all(sql, params) { return (await this.query(sql, params)).rows; }
  async get(sql, params) { return (await this.query(sql, params)).rows[0]; }

  async run(sql, params) {
    const r = await this.query(sql, params);
    return { changes: r.rowCount, rows: r.rows };
  }

  /** INSERT … and return the new row's id. */
  async insert(sql, params) {
    const r = await this.query(`${sql} RETURNING id`, params);
    return r.rows[0].id;
  }

  async exec(sql) { return this.driver.exec(sql); }

  /**
   * Runs fn(txDb) in a SERIALIZABLE transaction, retrying on serialization
   * conflicts. Inside fn, use the txDb argument for every query.
   */
  async tx(fn) {
    if (this.inTransaction) return fn(this);
    for (let attempt = 1; ; attempt++) {
      try {
        return await this.driver.transaction((txDriver) => fn(new Database(txDriver, { inTransaction: true })));
      } catch (err) {
        if (!RETRYABLE.has(err.code) || attempt >= 5) throw err;
        await new Promise((r) => setTimeout(r, 10 * attempt + Math.random() * 20));
      }
    }
  }

  async close() { return this.driver.close(); }
}

